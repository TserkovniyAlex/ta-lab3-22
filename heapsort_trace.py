"""ЛР3, варіант 22. Сортування купою з трасуванням обох фаз (Лістинг 3.2)."""

def swap(arr, i, j):
    """Міняє місцями два елементи в масиві."""
    arr[i], arr[j] = arr[j], arr[i]

def sink(arr, i, n):
    """Процедура занурення елемента вниз по купі (з трасуванням)."""
    k = i
    print(f"Починаємо 'занурювати' елемент: {arr[k]} з індексу {k}")
    while True:
        j = 2 * k + 1  # Індекс лівого дочірнього елемента
        if j >= n:
            print(f"Елемент {arr[k]} на індексі {k} досяг кінця купи. Завершуємо.")
            break
        print(f"  Обираємо лівий дочірній елемент: {arr[j]} на індексі {j}")
        # Знаходимо індекс найбільшого дочірнього елемента
        if j + 1 < n:
            if arr[j + 1] > arr[j]:
                print(f"  Порівнюємо {arr[j]} (лівий) та {arr[j + 1]} (правий). Обираємо {arr[j + 1]}")
                j += 1
            else:
                print(f"  Порівнюємо {arr[j]} (лівий) та {arr[j + 1]} (правий). Обираємо {arr[j]}")
        # Перевіряємо властивість максимальної купи
        if arr[k] >= arr[j]:
            print(f"  {arr[k]} (батько) >= {arr[j]} (найбільший дочірній). Елемент на своєму місці.")
            break
        print(f"  Міняємо місцями {arr[k]} (батько) та {arr[j]} (дочірній)")
        swap(arr, k, j)
        print(f"  Масив після обміну: {arr}")
        k = j

def heapsort(arr):
    """Алгоритм сортування купою (з трасуванням)."""
    n = len(arr)
    print(f"Початковий масив: {arr}")
    # Фаза 1: Побудова максимальної купи
    print("--- Фаза 1: Побудова максимальної купи ---\n")
    for i in range(n // 2 - 1, -1, -1):
        sink(arr, i, n)
        print("---------------------------------")
    print(f"\nМасив після побудови купи: {arr}\n")
    # Фаза 2: Сортування
    print("--- Фаза 2: Сортування ---\n")
    for i in range(n - 1, 0, -1):
        print(f"Міняємо місцями корінь ({arr[0]}) та останній елемент ({arr[i]})")
        swap(arr, 0, i)
        n -= 1
        print(f"Розмір купи зменшився до {n}. Відновлюємо властивості купи.")
        sink(arr, 0, n)
        print(f"Масив на поточному кроці: {arr}\n")
    return arr

# Моделювання
A = [19, 75, 43, 31, 5, 66, 62, 34, 76]
sorted_A = heapsort(A)
print(f"Відсортований масив: {sorted_A}")
